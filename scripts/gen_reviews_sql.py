"""Generate sql/02_ai_reviews.sql: ~50 synthetic customer reviews / store notes (no real data)."""
import random
random.seed(11)
STORES = {101: "Store 101", 104: "Store 104", 107: "Store 107", 112: "Store 112", 118: "Store 118", 123: "Store 123", 131: "Store 131", 138: "Store 138"}
T = {
 "out_of_stock": [
  ("Dairy", "The {store} had no {p} again this week. Shelf was empty on Tuesday and still empty on Friday."),
  ("Bread and bakery", "Third time in {n} days that {store} is out of {p}. I drove there only for that."),
  ("Beverages", "No {p} at {store} before the weekend, the whole row was empty. Please stock more when it is warm."),
  ("Fruit and vegetables", "{store} ran out of {p} by lunchtime. Staff said the next delivery is in {n} days."),
  ("Ready meals", "Hoppas ni fyller på {p} snart, hyllan på {store} har varit tom i {n} dagar."),
  ("Fish", "Wanted {p} for Christmas dinner but {store} was sold out already on the 20th."),
 ],
 "quality": [
  ("Fruit and vegetables", "The {p} I bought at {store} were soft and bruised, half went in the bin."),
  ("Meat", "{p} from {store} smelled off, the date was fine but it was clearly not fresh."),
  ("Dairy", "Opened the {p} at home, it was already sour two days before the best before date."),
  ("Bread and bakery", "The {p} at {store} was stale, it felt like yesterday's bread."),
  ("Fish", "The {p} had freezer burn on the edges, not what I expect from {store}."),
  ("Ready meals", "Maten från {store} var kall i mitten och smakade inte som vanligt."),
 ],
 "price": [
  ("Beverages", "{p} costs {pr} SEK at {store} but {pr2} SEK in the other chain. Hard to justify."),
  ("Meat", "The price of {p} went up to {pr} SEK per kilo, it was {pr2} SEK last month."),
  ("Snacks and candy", "{p} at {store} is {pr} SEK, the offer sign said {pr2} SEK but I was charged full price."),
  ("Dairy", "Why does {p} cost {pr} SEK now? Last week it was {pr2} SEK."),
  ("Household", "Dyrt! {p} kostar {pr} kr på {store}, jämfört med {pr2} kr tidigare."),
 ],
 "delivery": [
  ("Fruit and vegetables", "My online order from {store} arrived {n} hours late and the {p} was warm."),
  ("Frozen", "Home delivery from {store}: the {p} was half thawed when it arrived."),
  ("Dairy", "Delivery window was 17 to 19 but the driver came at {n} pm, and the {p} was missing."),
  ("Household", "Order from {store} was delivered to the wrong address, took {n} days to fix."),
  ("Beverages", "The courier left the {p} outside in the sun. No message, no call."),
  ("Personal care", "Leveransen från {store} kom {n} dagar för sent och {p} saknades."),
 ],
}
P = {"Dairy": ["milk", "yoghurt", "oat drink"], "Bread and bakery": ["sourdough", "cinnamon buns", "rye bread"],
     "Beverages": ["sparkling water", "iced tea", "cola"], "Fruit and vegetables": ["strawberries", "tomatoes", "avocados"],
     "Ready meals": ["lasagne", "meatballs", "fish soup"], "Fish": ["salmon", "herring", "shrimp"], "Meat": ["minced beef", "chicken fillets", "sausages"],
     "Snacks and candy": ["chips", "chocolate", "pick and mix"], "Household": ["washing powder", "toilet paper", "dish soap"],
     "Frozen": ["ice cream", "frozen peas", "pizza"], "Personal care": ["shampoo", "toothpaste", "hand soap"]}
OTHER = [
 ("Dairy", "Great selection and friendly staff at {store}, thank you!"),
 ("Bread and bakery", "Love the new bakery corner at {store}, the bread is still warm at 8 in the morning."),
 ("Fruit and vegetables", "Clean store, easy to find everything. Self checkout at {store} was quick."),
 ("Household", "Staff at {store} helped me carry my bags to the car. Very kind."),
]
rows, rid = [], 1
plan = [("out_of_stock", 14), ("quality", 11), ("price", 10), ("delivery", 10)]
for topic, n in plan:
    for i in range(n):
        g, tmpl = T[topic][i % len(T[topic])]
        store_id = random.choice(list(STORES))
        p = random.choice(P[g]); pr = random.randint(25, 120); pr2 = max(15, pr - random.randint(5, 25))
        txt = tmpl.format(store=STORES[store_id], p=p, n=random.randint(2, 6), pr=pr, pr2=pr2)
        rows.append((store_id, g, txt))
for g, tmpl in OTHER:
    store_id = random.choice(list(STORES)); rows.append((store_id, g, tmpl.format(store=STORES[store_id])))
random.shuffle(rows)
vals = []
for i, (sid, g, txt) in enumerate(rows, 1):
    d = f"2026-{random.choice([9,10,11]):02d}-{random.randint(1,28):02d}"
    vals.append("  (%d, %d, '%s', '%s', DATE'%s')" % (i, sid, g.replace("'", "''"), txt.replace("'", "''"), d))
sql = "-- Generated by scripts/gen_reviews_sql.py. Synthetic reviews, no real data.\nCREATE OR REPLACE TABLE ${catalog}.${schema}.customer_reviews\nCOMMENT 'Synthetic customer reviews and store notes for the AI Functions demo. Not real data.'\nAS SELECT * FROM VALUES\n" + ",\n".join(vals) + "\nAS t(review_id, store_id, product_group, review_text, review_date);\n"
open("sql/02_reviews_data.sql", "w").write(sql)
print(len(rows), "reviews")
